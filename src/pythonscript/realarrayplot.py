def parse_teensy_csv(raw, col):
    records = []

    for line in raw.strip().splitlines():
        line = line.strip()

        if line.startswith("Teensy:"):
            line = line.replace("Teensy:", "", 1).strip()

        if line == "":
            continue
        if line.startswith("ROW_END"):
            continue
        if line.startswith("Press Enter"):
            continue
        if line.startswith("time_us"):
            continue
        if line.startswith("End of test"):
            continue

        parts = [p.strip() for p in line.split(",")]

        # old format: time_us,row,adc_voltage
        if len(parts) == 3:
            time_us, row, adc_voltage = parts
            time_us = int(time_us)

            if time_us < 500000:
                phase = "before"
            elif time_us < 1500000:
                phase = "on"
            else:
                phase = "after"

        # new format: time_us,row,phase,adc_voltage
        elif len(parts) == 4:
            time_us, row, phase, adc_voltage = parts
            time_us = int(time_us)

        else:
            print("Skipping:", line)
            continue

        records.append({
            "time_us": time_us,
            "time_s": time_us / 1e6,
            "row": int(row),
            "col": col,
            "phase": phase,
            "adc_voltage": float(adc_voltage),
        })

    return pd.DataFrame(records)


